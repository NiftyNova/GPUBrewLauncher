"""Build the launcher's antialiased type atlas (no runtime font dependency)."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parent / 'shaders'
atlas = Image.new('L', (1024, 2048))
draw = ImageDraw.Draw(atlas)
font = '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'
labels = [
    ('TITLE', 'GPUBrewLauncher', 88),
    ('SUBTITLE', 'NiftyFork V1.0.0', 24),
    ('PLATFORM', 'N I N T E N D O   S W I T C H   2', 16),
    ('LIBRARY', 'Your library', 26),
    ('COUNT1', '1 title', 18),
    ('COUNT2', '2 titles', 18),
    ('COUNT3', '3 titles', 18),
    ('APPS', 'Apps', 18),
    ('NOTITLES', 'No titles found', 34),
    ('EMPTYHINT', 'Your library is empty.', 20),
    ('SELECT', 'Select', 19),
    ('BACK', 'Back', 19),
    ('EMPTY', 'App unavailable', 34),
    ('DETAIL', 'Refresh the app list and try again.', 19),
    ('CLOSE', 'Press B to return', 18),
    ('BUTTON_A', 'A', 16),
    ('BUTTON_B', 'B', 16),
    ('CREDIT', 'Created W/AI (@RavensClawX) - Forked by NiftyNova', 15),

]
labels += [(f'DIGIT{i}', str(i), 34) for i in range(10)]
header = ['// Generated by homebrew-launcher/launcher-text.py. Atlas pixels follow the 1024-byte state buffer.']
y = 2
for name, text, size in labels:
    face = ImageFont.truetype(font, size)
    box = draw.textbbox((0, 0), text, font=face)
    width, height = box[2] - box[0], box[3] - box[1]
    assert width + 4 <= 1024 and y + height + 2 <= 2048
    draw.text((2 - box[0], y - box[1]), text, fill=255, font=face)
    header.append(f'const ivec4 TEXT_{name} = ivec4(2, {y}, {width}, {height});')
    y += height + 8
header.append('const ivec4 DIGITS[10] = ivec4[10](' + ','.join(f'TEXT_DIGIT{i}' for i in range(10)) + ');')
(root / 'launcher-text.bin').write_bytes(atlas.tobytes())
(root / 'launcher-text.glsl').write_text('\n'.join(header) + '\n')
atlas.save(root / 'launcher-text.png')
print(f'Type atlas: 1024 x 2048, {y} rows used')
